export function validateTheme(theme: unknown): theme is ThemeDefinition {
  if (!theme || typeof theme !== 'object') return false;
  const t = theme as Partial<ThemeDefinition>;
  return (
    typeof t.id === 'string' &&
    typeof t.name === 'string' &&
    (t.type === 'dark' || t.type === 'light') &&
    typeof t.background === 'string' &&
    typeof t.foreground === 'string' &&
    typeof t.syntax === 'object' &&
    t.syntax !== null
  );
}

export function getThemeById(id: string): ThemeDefinition {
  return THEME_REGISTRY[id] || THEME_REGISTRY['tokyo-night'];
}

export function listThemes(): ThemeDefinition[] {
  return Object.values(THEME_REGISTRY);
}

export function registerTheme(theme: ThemeDefinition): void {
  if (!validateTheme(theme)) {
    throw new Error(`Invalid theme definition for "${(theme as any)?.id || 'unknown'}"`);
  }
  THEME_REGISTRY[theme.id] = theme;
}
